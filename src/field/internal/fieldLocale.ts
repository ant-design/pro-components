type FieldLocaleKey = keyof typeof fieldLocaleMessages;

const localeKeys = Object.keys(fieldLocaleMessages) as FieldLocaleKey[];
const preferredPrefix: Record<string, FieldLocaleKey> = {
  en: 'en-US',
  zh: 'zh-CN',
};

export function findFieldLocaleKey(locale?: string): FieldLocaleKey {
  const input = (locale || 'zh-CN').replace('_', '-').toLowerCase();
  const exact = localeKeys.find((key) => key.toLowerCase() === input);
  if (exact) return exact;
  const prefix = input.split('-')[0];
  return (
    preferredPrefix[prefix] ??
    localeKeys.find((key) => key.toLowerCase().startsWith(prefix + '-')) ??
    'zh-CN'
  );
}

const defaultMessages: Record<string, string> = fieldLocaleMessages['zh-CN'];

export const fieldIntlMap: Record<FieldLocaleKey, IntlType> =
  Object.fromEntries(
    localeKeys.map((locale) => {
      const messages: Record<string, string> = fieldLocaleMessages[locale];
      return [
        locale,
        {
          locale,
          getMessage: (id: string, defaultMessage: string) =>
            messages[id] ?? defaultMessages[id] ?? defaultMessage,
        },
      ];
    }),
  ) as Record<FieldLocaleKey, IntlType>;
